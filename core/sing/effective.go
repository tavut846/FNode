const (
	EffectiveSuffix = ".effective.json"
	PanelSuffix     = ".panel.json"
	// MetaKey holds FNode's notes inside an effective file. sing-box would
	// reject it, so the file is for reading, not for running.
	MetaKey = "_fnode"
)

// OutboundOrigin records where one merged outbound came from.
type OutboundOrigin struct {
	Tag    string `json:"tag"`
	Type   string `json:"type"`
	Source string `json:"source"`
	Node   string `json:"node,omitempty"`
}

// EffectiveMeta is the MetaKey object of an effective file.
type EffectiveMeta struct {
	Node        string           `json:"node"`
	GeneratedAt string           `json:"generated_at"`
	Note        string           `json:"note"`
	Counts      map[string]int   `json:"outbound_counts"`
	Rules       int              `json:"rules"`
	Outbounds   []OutboundOrigin `json:"outbounds"`
}

var unsafeFileChars = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

// NodeFileStem turns a node tag such as "[https://panel]-vless:1" into a safe
// file name stem ("https_panel_-vless_1").
func NodeFileStem(tag string) string {
	s := strings.Trim(unsafeFileChars.ReplaceAllString(tag, "_"), "_.")
	if s == "" {
		s = "node"
	}
	return s
}

// writeFileAtomic writes data to a temp file in the same directory and renames
// it over path, so readers never see a partial file. The temp name ends in
// .tmp, which the config watcher ignores.
func writeFileAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	if _, err = tmp.Write(data); err == nil {
		err = tmp.Sync()
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Chmod(tmpName, 0o600)
	}
	if err == nil {
		err = os.Rename(tmpName, path)
	}
	if err != nil {
		_ = os.Remove(tmpName)
	}
	return err
}

// protectedPaths are files the generated output must never overwrite.
func (b *Sing) protectedPaths() []string {
	var paths []string
	if b.coreConfig != nil && b.coreConfig.SingConfig != nil && b.coreConfig.SingConfig.OriginalPath != "" {
		if abs, err := filepath.Abs(b.coreConfig.SingConfig.OriginalPath); err == nil {
			paths = append(paths, abs)
		}
	}
	return paths
}

func (b *Sing) generatedDir() string {
	if b.coreConfig == nil || b.coreConfig.SingConfig == nil {
		return ""
	}
	return b.coreConfig.SingConfig.GeneratedDir
}

// nodeDump is the per-node input of the dump, copied under the user lock.
type nodeDump struct {
	tag     string
	info    *panel.NodeInfo
	inbound map[string]any
}

// marshalRaw converts a sing-box option value to a generic JSON map.
func (b *Sing) marshalRaw(v any) (map[string]any, error) {
	data, err := json.MarshalContext(b.ctx, v)
	if err != nil {
		return nil, err
	}
	var m map[string]any
	if err = stdjson.Unmarshal(data, &m); err != nil {
		return nil, err
	}
	return m, nil
}

// buildEffective returns the effective config document of one node.
func (b *Sing) buildEffective(n nodeDump, state *appliedState, now time.Time) (map[string]any, error) {
	outbounds := make([]any, 0, len(state.Outbounds))
	origins := make([]OutboundOrigin, 0, len(state.Outbounds))
	for _, e := range state.Outbounds {
		outbounds = append(outbounds, e.Raw)
		origins = append(origins, OutboundOrigin{Tag: e.Tag, Type: e.Type, Source: e.Source, Node: e.Node})
	}
	rules := make([]any, 0, len(state.Rules)+len(b.originRules))
	for _, r := range state.Rules {
		rules = append(rules, r)
	}
	for _, r := range b.originRules {
		m, err := b.marshalRaw(r)
		if err != nil {
			return nil, fmt.Errorf("marshal origin rule: %w", err)
		}
		rules = append(rules, m)
	}
	route := map[string]any{"rules": rules}
	if b.routeFinal != "" {
		route["final"] = b.routeFinal
	}
	if len(b.originRuleSets) > 0 {
		sets := make([]any, 0, len(b.originRuleSets))
		for _, rs := range b.originRuleSets {
			m, err := b.marshalRaw(rs)
			if err != nil {
				return nil, fmt.Errorf("marshal origin rule set: %w", err)
			}
			sets = append(sets, m)
		}
		route["rule_set"] = sets
	}
	doc := map[string]any{
		MetaKey: EffectiveMeta{
			Node:        n.tag,
			GeneratedAt: now.Format(time.RFC3339),
			Note:        "Generated by FNode after every apply, for reading only. Edit config.json or sing_origin.json, or the panel, instead.",
			Counts:      state.Counts,
			Rules:       len(rules),
			Outbounds:   origins,
		},
		"outbounds": outbounds,
		"route":     route,
	}
	if n.inbound != nil {
		doc["inbounds"] = []any{n.inbound}
	}
	return doc, nil
}

// buildPanelDump returns the raw panel routing data of one node.
func buildPanelDump(n nodeDump, now time.Time) map[string]any {
	doc := map[string]any{
		"node":         n.tag,
		"generated_at": now.Format(time.RFC3339),
	}
	if n.info != nil && n.info.Common != nil {
		cm := n.info.Common
		doc["routes"] = nonNil(cm.Routes)
		doc["custom_outbounds"] = nonNil(cm.CustomOutbounds)
		doc["custom_routes"] = nonNil(cm.CustomRoutes)
		doc["custom_route_rules"] = nonNil(cm.CustomRouteRules)
	}
	return doc
}

func nonNil[T any](s []T) []T {
	if s == nil {
		return []T{}
	}
	return s
}

// writeEffectiveFiles writes <stem>.effective.json and <stem>.panel.json for
// every node after an apply. With prune, files of nodes that are gone are
// removed. Errors are logged, never returned: the dump is for debugging.
func (b *Sing) writeEffectiveFiles(prune bool) {
	dir := b.generatedDir()
	if dir == "" || b.last == nil {
		return
	}
	b.users.mapLock.RLock()
	nodes := make([]nodeDump, 0, len(b.inboundInfo))
	for tag, info := range b.inboundInfo {
		n := nodeDump{tag: tag, info: info}
		if opt, ok := b.inboundOptions[tag]; ok {
			if m, err := b.marshalRaw(opt); err == nil {
				delete(m, "users")
				n.inbound = m
			}
		}
		nodes = append(nodes, n)
	}
	b.users.mapLock.RUnlock()
	sort.Slice(nodes, func(i, j int) bool { return nodes[i].tag < nodes[j].tag })

	protected := b.protectedPaths()
	now := time.Now()
	keep := make(map[string]bool)
	for _, n := range nodes {
		stem := NodeFileStem(n.tag)
		effective, err := b.buildEffective(n, b.last, now)
		if err != nil {
			log.WithFields(log.Fields{"tag": n.tag, "err": err}).Warn("Build effective config failed")
			continue
		}
		files := map[string]any{
			filepath.Join(dir, stem+EffectiveSuffix): effective,
			filepath.Join(dir, stem+PanelSuffix):     buildPanelDump(n, now),
		}
		for path, doc := range files {
			keep[filepath.Base(path)] = true
			if isProtected(path, protected) {
				log.WithField("path", path).Error("Refusing to write a generated file over a source config file")
				continue
			}
			data, err := stdjson.MarshalIndent(doc, "", "  ")
			if err != nil {
				log.WithFields(log.Fields{"path": path, "err": err}).Warn("Marshal generated file failed")
				continue
			}
			if err = writeFileAtomic(path, append(data, '\n')); err != nil {
				log.WithFields(log.Fields{"path": path, "err": err}).Warn("Write generated file failed")
				continue
			}
		}
		log.WithFields(log.Fields{"tag": n.tag, "file": filepath.Join(dir, stem+EffectiveSuffix)}).Debug("Wrote effective config")
	}
	if prune {
		entries, _ := os.ReadDir(dir)
		for _, e := range entries {
			name := e.Name()
			if e.IsDir() || keep[name] || !(strings.HasSuffix(name, EffectiveSuffix) || strings.HasSuffix(name, PanelSuffix)) {
				continue
			}
			_ = os.Remove(filepath.Join(dir, name))
		}
	}
}

func isProtected(path string, protected []string) bool {
	abs, err := filepath.Abs(path)
	if err != nil {
		return true
	}
	for _, p := range protected {
		if strings.EqualFold(abs, p) {
			return true
		}
	}
	return false
}

// ReadEffectiveFiles reads the effective files in dir, sorted by node tag.
func ReadEffectiveFiles(dir string) ([]EffectiveFile, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []EffectiveFile
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), EffectiveSuffix) {
			continue
		}
		path := filepath.Join(dir, e.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		var doc struct {
			Meta EffectiveMeta `json:"_fnode"`
		}
		if err = stdjson.Unmarshal(data, &doc); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		files = append(files, EffectiveFile{
			Path: path,
			Stem: strings.TrimSuffix(e.Name(), EffectiveSuffix),
			Meta: doc.Meta,
			Data: data,
		})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Meta.Node < files[j].Meta.Node })
	return files, nil
}

// EffectiveFile is one effective file read back from disk.
type EffectiveFile struct {
	Path string
	Stem string
	Meta EffectiveMeta
	Data []byte
}

// Matches reports whether a --node filter selects this file: the exact node
// tag, the file stem, or a substring of the tag.
func (f EffectiveFile) Matches(filter string) bool {
	if filter == "" {
		return true
	}
	return f.Meta.Node == filter || f.Stem == filter || f.Stem == NodeFileStem(filter) ||
		strings.Contains(f.Meta.Node, filter)
}
